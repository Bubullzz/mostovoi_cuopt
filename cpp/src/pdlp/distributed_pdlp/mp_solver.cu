int run_mp_solve(const cuopt::mathematical_optimization::io::mps_data_model_t<int, double>& mps_data_model,
                 cuopt::mathematical_optimization::solver_settings_t<int, double>& settings,
                 mp_context_t& mp)
{
  assert(cuopt::mathematical_optimization::get_memory_backend_type() ==
         cuopt::mathematical_optimization::memory_backend_t::GPU);
  auto handle_ptr = std::make_unique<raft::handle_t>();

  auto pdlp_settings = settings.get_pdlp_settings();
  auto lp_timer      = cuopt::timer_t(pdlp_settings.time_limit);

  // Shared across the master-only block and the subsequent MPI_Bcast. Master
  // fills them inside the if-block; shards receive them via the broadcast.
  int n_cstr = 0;
  int n_vars = 0;
  int nnz    = 0;
  std::vector<int>    parts;
  // Constraint matrix (A) + its transpose (A^T), both as host-side CSR.
  std::vector<int>    h_A_row_offsets;
  std::vector<int>    h_A_col_indices;
  std::vector<double> h_A_values;
  std::vector<int>    h_A_t_row_offsets;
  std::vector<int>    h_A_t_col_indices;
  std::vector<double> h_A_t_values;
  // Variable-indexed (size n_vars) and constraint-indexed (size n_cstr) data.
  std::vector<double> h_obj;
  std::vector<double> h_var_lb;
  std::vector<double> h_var_ub;
  std::vector<double> h_cstr_lb;
  std::vector<double> h_cstr_ub;
  // Problem-level scalars. maximize is a bool at the API, but we transport
  // it as a double (0.0/1.0) so all 3 scalars pack into one MPI_Bcast.
  bool   maximize                 = false;
  double objective_offset         = 0.0;
  double objective_scaling_factor = 1.0;

  if (mp.is_master()) {
    const bool run_presolve = pdlp_settings.presolver != presolver_t::None;
    std::unique_ptr<mip::third_party_presolve_t<int, double>> presolver_ptr;
    std::optional<mip::third_party_presolve_host_result_t<int, double>> host_res;
    [[maybe_unused]] double presolve_time = 0.0;

    if (run_presolve) {
      // mirroring single-GPU solve.cu
      const double presolve_time_limit =
        std::max(1.0, std::min(0.1 * lp_timer.remaining_time(), 60.0));

      presolver_ptr = std::make_unique<mip::third_party_presolve_t<int, double>>();
      host_res      = presolver_ptr->apply_presolve_from_mps_data(
        mps_data_model,
        cuopt::mathematical_optimization::problem_category_t::LP,
        pdlp_settings.presolver,
        pdlp_settings.dual_postsolve,
        pdlp_settings.tolerances.absolute_primal_tolerance,
        pdlp_settings.tolerances.relative_primal_tolerance,
        presolve_time_limit);

      // TODO(MP): wire terminal_solution_from_presolve_status from solve.cu
      // (currently static there). For now, early-exit here means we lose
      // the terminal solution — presolve_only exits report "not implemented".
      // if (auto terminal = terminal_solution_from_presolve_status<int, double>(
      //       host_res->status, handle_ptr->get_stream())) {
      //   return std::move(*terminal);
      // }

      // Presolve completely solved the problem.
      if (host_res->reduced_problem.get_n_variables() == 0 &&
          host_res->reduced_problem.get_n_constraints() == 0) {
        CUOPT_LOG_INFO("Presolve completely solved the problem");
        presolve_time = lp_timer.elapsed_time();
        CUOPT_LOG_INFO("%s presolve time: %.2fs",
                       pdlp_settings.presolver == presolver_t::PSLP ? "PSLP" : "Papilo",
                       presolve_time);

        // Postsolve is host-side here (no reduced GPU problem was ever built);
        // bounce the resulting vectors to device to satisfy the solution API.
        std::vector<double> h_primal, h_dual, h_rc;
        presolver_ptr->undo(h_primal,
                            h_dual,
                            h_rc,
                            cuopt::mathematical_optimization::problem_category_t::LP,
                            /*status_to_skip=*/false,
                            pdlp_settings.dual_postsolve);
        auto primal_uv = cuopt::device_copy(h_primal, handle_ptr->get_stream());
        auto dual_uv   = cuopt::device_copy(h_dual, handle_ptr->get_stream());
        auto rc_uv     = cuopt::device_copy(h_rc, handle_ptr->get_stream());
        handle_ptr->sync_stream();
      }

      presolve_time = lp_timer.elapsed_time();
      CUOPT_LOG_INFO("%s presolve time: %.2fs",
                     pdlp_settings.presolver == presolver_t::PSLP ? "PSLP" : "Papilo",
                     presolve_time);
    }
    const auto& mps = run_presolve ? host_res->reduced_problem : mps_data_model;
    n_vars          = static_cast<int>(mps.get_objective_coefficients().size());
    n_cstr          = static_cast<int>(mps.get_constraint_lower_bounds().size());
    nnz             = static_cast<int>(mps.get_constraint_matrix_values().size());

    // A (CSR) — mutable copies for the engine + partitioner consumers below.
    h_A_row_offsets = mps.get_constraint_matrix_offsets();
    h_A_col_indices = mps.get_constraint_matrix_indices();
    h_A_values      = mps.get_constraint_matrix_values();

    // Bounds + objective, straight off the (reduced) mps. These are the
    // vectors every shard will slice via rank_data.local_to_global_{var,cstr}
    // inside the pdlp_solver_t MP ctor.
    h_obj                    = mps.get_objective_coefficients();
    h_var_lb                 = mps.get_variable_lower_bounds();
    h_var_ub                 = mps.get_variable_upper_bounds();
    h_cstr_lb                = mps.get_constraint_lower_bounds();
    h_cstr_ub                = mps.get_constraint_upper_bounds();
    maximize                 = mps.get_sense();
    objective_offset         = mps.get_objective_offset();
    objective_scaling_factor = mps.get_objective_scaling_factor();

    // ----- 2. Transpose A -> A^T on the host (one-shot CSR transpose) -----
    // CSC(A) and CSR(A^T) share the same memory layout, so the CSC produced
    // by csr_matrix_t::to_compressed_col IS the CSR of A^T.
    // O(nnz + n_vars) counting sort, same as problem_t::compute_transpose.
    namespace ds = cuopt::mathematical_optimization;
    ds::csr_matrix_t<int, double> A_csr(n_cstr, n_vars, nnz);
    A_csr.row_start = h_A_row_offsets;
    A_csr.j         = h_A_col_indices;
    A_csr.x         = h_A_values;
    ds::csc_matrix_t<int, double> AT_as_csc(n_vars, n_cstr, nnz);
    A_csr.to_compressed_col(AT_as_csc);
    h_A_t_row_offsets = std::move(AT_as_csc.col_start);
    h_A_t_col_indices = std::move(AT_as_csc.i);
    h_A_t_values      = std::move(AT_as_csc.x);

    // ----- 3. Partition -----
    partitioner_input_t<int, double> partition_input;
    partition_input.nb_cstr  = n_cstr;
    partition_input.nb_vars  = n_vars;
    partition_input.nb_parts = mp.world_size;

    // Resolve which partitioner to use. The public enum is validated at the
    // parameter-set layer (int_parameters min/max), so we only need to map
    // the three known values to the backend selector.
    partitioner_kind_t kind;
    switch (pdlp_settings.multigpu_pdlp_partitioner) {
      case multigpu_pdlp_partitioner_t::Auto:
        kind = (mp.world_size == 1) ? partitioner_kind_t::RoundRobin
                                    : partitioner_kind_t::KaMinPar;
        break;
      case multigpu_pdlp_partitioner_t::KaMinPar: kind = partitioner_kind_t::KaMinPar; break;
      case multigpu_pdlp_partitioner_t::RoundRobin: kind = partitioner_kind_t::RoundRobin; break;
      default:
        cuopt_expects(false,
                      error_type_t::ValidationError,
                      "Unknown multigpu_pdlp_partitioner value %d",
                      static_cast<int>(pdlp_settings.multigpu_pdlp_partitioner));
        kind = partitioner_kind_t::RoundRobin;  // unreachable; silences -Wmaybe-uninitialized
    }
    // csr_host_view_t members are std::span<const int>, an owning
    // std::vector<int> converts implicitly.
    partition_input.A.row_offsets   = h_A_row_offsets;
    partition_input.A.col_indices   = h_A_col_indices;
    partition_input.A.num_rows      = n_cstr;
    partition_input.A.num_cols      = n_vars;
    partition_input.A_t.row_offsets = h_A_t_row_offsets;
    partition_input.A_t.col_indices = h_A_t_col_indices;
    partition_input.A_t.num_rows    = n_vars;
    partition_input.A_t.num_cols    = n_cstr;
    // 0 => KaMinPar auto-detects and uses all hardware threads.
    partition_input.nb_threads = 0;
    CUOPT_LOG_TRACE(
      "Partitioning %d constraints + %d variables into %d part(s) using the %s "
      "partitioner",
      n_cstr,
      n_vars,
      mp.world_size,
      (kind == partitioner_kind_t::RoundRobin) ? "round_robin"
      : (kind == partitioner_kind_t::KaMinPar) ? "kaminpar"
                                               : "unknown");
    auto partitioner = make_partitioner<int, double>(kind);
    parts            = partitioner->partition(partition_input);
  }

  // Option A: broadcast the full host-side matrix + partition from master to
  // every shard, then each rank runs the (unchanged) slicing algorithm and
  // keeps only its own slice. See create_rank_data_for_rank for why the
  // slicing can't easily be made per-rank-only without rewriting the halo
  // plan computation.
  //
  // Shape first (so shards can size their receive buffers), then parts, then
  // each matrix buffer. All collective; must be called by every rank.
  if (mp.is_mpi()) {
    // 1. Shape first, so shards can size every receive buffer below.
    int shape[3] = {n_cstr, n_vars, nnz};
    CUOPT_MPI_TRY(MPI_Bcast(shape, 3, MPI_INT, 0, mp.world_comm));
    n_cstr = shape[0];
    n_vars = shape[1];
    nnz    = shape[2];

    // 2. Shard-side allocation. Master's buffers are already filled.
    if (!mp.is_master()) {
      parts.resize(static_cast<std::size_t>(n_cstr) + static_cast<std::size_t>(n_vars));
      h_A_row_offsets.resize(n_cstr + 1);
      h_A_col_indices.resize(nnz);
      h_A_values.resize(nnz);
      h_A_t_row_offsets.resize(n_vars + 1);
      h_A_t_col_indices.resize(nnz);
      h_A_t_values.resize(nnz);
      h_obj.resize(n_vars);
      h_var_lb.resize(n_vars);
      h_var_ub.resize(n_vars);
      h_cstr_lb.resize(n_cstr);
      h_cstr_ub.resize(n_cstr);
    }

    // 3. Partition + matrix (A, A^T).
    bcast(parts, mp);
    bcast(h_A_row_offsets, mp);
    bcast(h_A_col_indices, mp);
    bcast(h_A_values, mp);
    bcast(h_A_t_row_offsets, mp);
    bcast(h_A_t_col_indices, mp);
    bcast(h_A_t_values, mp);

    // 4. Bounds + objective.
    bcast(h_obj, mp);
    bcast(h_var_lb, mp);
    bcast(h_var_ub, mp);
    bcast(h_cstr_lb, mp);
    bcast(h_cstr_ub, mp);

    // 5. Problem-level scalars, packed into one 3-double message
    //    (bool->double is lossless for 0.0/1.0).
    double scalars[3] = {maximize ? 1.0 : 0.0, objective_offset, objective_scaling_factor};
    CUOPT_MPI_TRY(MPI_Bcast(scalars, 3, MPI_DOUBLE, 0, mp.world_comm));
    if (!mp.is_master()) {
      maximize                 = (scalars[0] != 0.0);
      objective_offset         = scalars[1];
      objective_scaling_factor = scalars[2];
    }
  }

  // Every rank computes the full slicing and keeps only its own slice.
  auto rank_data = create_rank_data_for_rank<int, double>(parts,
                                                          h_A_row_offsets,
                                                          h_A_col_indices,
                                                          h_A_values,
                                                          h_A_t_row_offsets,
                                                          h_A_t_col_indices,
                                                          h_A_t_values,
                                                          mp.world_size,
                                                          n_cstr,
                                                          n_vars,
                                                          nnz,
                                                          mp.rank);

  CUOPT_LOG_INFO("rank %d: owns %d constraints, %d variables (total %d / %d after halo)",
                 mp.rank,
                 rank_data.owned_cstr_size,
                 rank_data.owned_var_size,
                 rank_data.total_cstr_size,
                 rank_data.total_var_size);

  // Collective: every rank must reach this call. The returned handle owns
  // the comm; dropping it runs ncclCommDestroy on the right device. Moved
  // into distributed_state_t below.
  auto nccl_comm = make_nccl_comm(mp);
  CUOPT_LOG_TRACE("rank %d: NCCL comm initialized (world_size=%d)", mp.rank, mp.world_size);

  // Everything the per-rank solver needs to run collectives (comm + rank
  // identity + its slice of the problem + per-peer halo staging buffers,
  // allocated on handle_ptr's stream from rank_data). Owned here; will be
  // moved into pdlp_solver_t once that ctor path accepts a
  // distributed_state_t.
  distributed_state_t<int, double> dist{mp.world_size,
                                        mp.rank,
                                        mp.device_id,
                                        std::move(nccl_comm),
                                        std::move(rank_data),
                                        handle_ptr->get_stream()};

  // ----- Build the LOCAL problem_t this rank hands to pdlp_solver_t -----
  // Transplanted from pdlp_shard_t's ctor body (shard.cu:43-125). We skip
  // adding a new "MP ctor" on pdlp_solver_t -- the EXISTING single-GPU ctor
  // with is_distributed_sub_pdlp=true already does the right thing for a
  // per-rank peer. Once this path is proven, pdlp_shard_t + the SP-mGPU
  // orchestrator ctor at pdlp.cu:410+ can be deleted.
  const auto& rd = dist.rank_data;

  // 1. Gather per-shard host slices sized to TOTAL (owned + halo). Owned
  //    slots get real values; halo slots keep defaults (±inf / 0) because
  //    they must not be read before a halo exchange fills them.
  std::vector<double> h_shard_obj(rd.total_var_size, 0.0);
  std::vector<double> h_shard_var_lb(rd.total_var_size,
                                     -std::numeric_limits<double>::infinity());
  std::vector<double> h_shard_var_ub(rd.total_var_size,
                                     std::numeric_limits<double>::infinity());
  std::vector<double> h_shard_cstr_lb(rd.total_cstr_size,
                                      -std::numeric_limits<double>::infinity());
  std::vector<double> h_shard_cstr_ub(rd.total_cstr_size,
                                      std::numeric_limits<double>::infinity());
  for (int i = 0; i < rd.owned_var_size; ++i) {
    const auto g      = rd.local_to_global_var[i];
    h_shard_obj[i]    = h_obj[g];
    h_shard_var_lb[i] = h_var_lb[g];
    h_shard_var_ub[i] = h_var_ub[g];
  }
  for (int i = 0; i < rd.owned_cstr_size; ++i) {
    const auto g       = rd.local_to_global_cstr[i];
    h_shard_cstr_lb[i] = h_cstr_lb[g];
    h_shard_cstr_ub[i] = h_cstr_ub[g];
  }

  // 2. Build optimization_problem_t sized to TOTAL on this process's device.
  //    Lives in this frame for the solver's lifetime (opt_problem is
  //    retained for the same reason pdlp_shard_t owns it as a struct field).
  optimization_problem_t<int, double> opt_problem(handle_ptr.get());
  opt_problem.set_csr_constraint_matrix(rd.h_A_values.data(),
                                        static_cast<int>(rd.h_A_values.size()),
                                        rd.h_A_col_indices.data(),
                                        static_cast<int>(rd.h_A_col_indices.size()),
                                        rd.h_A_row_offsets.data(),
                                        static_cast<int>(rd.h_A_row_offsets.size()));
  opt_problem.set_objective_coefficients(h_shard_obj.data(), rd.total_var_size);
  opt_problem.set_variable_lower_bounds(h_shard_var_lb.data(), rd.total_var_size);
  opt_problem.set_variable_upper_bounds(h_shard_var_ub.data(), rd.total_var_size);
  opt_problem.set_constraint_lower_bounds(h_shard_cstr_lb.data(), rd.total_cstr_size);
  opt_problem.set_constraint_upper_bounds(h_shard_cstr_ub.data(), rd.total_cstr_size);
  opt_problem.set_maximize(maximize);
  opt_problem.set_objective_offset(objective_offset);
  opt_problem.set_objective_scaling_factor(objective_scaling_factor);
  opt_problem.set_problem_category(problem_category_t::LP);

  // 3. Wrap in mip::problem_t (what pdlp_solver_t consumes).
  mip::problem_t<int, double> sub_problem(opt_problem);

  // 4. Override reverse_* (A^T) with the pre-sliced LOCAL A^T from rank_data.
  //    problem_t's ctor computes a transpose of the LOCAL A, which is wrong
  //    in distributed mode: A_local is owned_cstr x total_var, and A^T_local
  //    is the owned_var x total_cstr slice we built during partitioning
  //    (see shard.cu:104-108).
  auto stream = handle_ptr->get_stream();
  sub_problem.reverse_offsets.resize(rd.h_A_t_row_offsets.size(), stream);
  sub_problem.reverse_constraints.resize(rd.h_A_t_col_indices.size(), stream);
  sub_problem.reverse_coefficients.resize(rd.h_A_t_values.size(), stream);
  raft::copy(sub_problem.reverse_offsets.data(),
             rd.h_A_t_row_offsets.data(),
             rd.h_A_t_row_offsets.size(),
             stream);
  raft::copy(sub_problem.reverse_constraints.data(),
             rd.h_A_t_col_indices.data(),
             rd.h_A_t_col_indices.size(),
             stream);
  raft::copy(sub_problem.reverse_coefficients.data(),
             rd.h_A_t_values.data(),
             rd.h_A_t_values.size(),
             stream);
  handle_ptr->sync_stream(stream);

  // 5. Build the solver via the EXISTING single-GPU ctor with the shard
  //    flag. is_distributed_sub_pdlp=true opts out of (see pdlp.cu:204/216/370):
  //      - pdhg_solver_t:              distributed path toggle
  //      - initial_scaling_strategy_:  local Ruiz / Pock-Chambolle (incoherent across ranks)
  //      - problem representation:     CSR/CSC transpose check (A/A^T are independent slices)
  //    All three are exactly what we want for an MP peer.
  pdlp_solver_t<int, double> solver(sub_problem,
                                    pdlp_settings,
                                    /*is_legacy_batch_mode=*/false,
                                    /*is_distributed_sub_pdlp=*/true);
  CUOPT_LOG_TRACE("rank %d: pdlp_solver_t constructed (shard-mode)", mp.rank);

  // TODO(MP): the solver is constructed but has no handle to `dist` yet, so
  // calling solver.run_solver(lp_timer) would run an isolated single-GPU
  // iteration over this rank's partial problem (wrong). Next step: add
  // std::optional<distributed_state_t<i_t,f_t>> dist_ as a member of
  // pdlp_solver_t and port multi_gpu_engine_t's distributed primitives
  // (halo_exchange_{var,cstr}, allreduce_sum, distributed_dot,
  // distributed_l2_norm, distributed_spmv_A{,t}) to methods on
  // distributed_state_t, dispatched at the ~20-30 call sites in the
  // iteration loop. Finally gather + postsolve on master.
  return 0;
}

