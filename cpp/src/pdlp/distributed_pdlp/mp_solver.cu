// Standard MPI-launched NCCL bootstrap:
//   1) master generates an opaque unique id,
//   2) MPI_Bcast it to every rank,
//   3) each rank calls ncclCommInitRank with its own (world_size, rank).
// Returned handle owns the comm; its deleter does the matching
// ncclCommDestroy on the right device (see nccl_comm_deleter_t in
// nccl_helpers.hpp) so it's safe to move into distributed_state_t or drop
// on exception.
//
// Collective: must be called by every rank in mp.world_comm.
// ncclCommInitRank blocks until every rank arrives, so any earlier-exiting
// branch upstream will hang the others here.
// Precondition: cudaSetDevice(mp.device_id) is already in effect
// (mp_context_t's ctor arranges this).
nccl_comm_unique_ptr_t make_nccl_comm(const mp_context_t& mp)
{
  cuopt_expects(mp.is_mpi(),
                error_type_t::ValidationError,
                "make_nccl_comm: mp_context_t has status=MPI_UNUSED (not under MPI)");

  // Nccl meeting Id generated by master then bcasted to everyone
  ncclUniqueId id;
  if (mp.is_master()) { CUOPT_NCCL_TRY(ncclGetUniqueId(&id)); }
  CUOPT_MPI_TRY(MPI_Bcast(&id, sizeof(id), MPI_BYTE, 0, mp.world_comm));

  ncclComm_t raw = nullptr;
  CUOPT_NCCL_TRY(ncclCommInitRank(&raw, mp.world_size, id, mp.rank));
  return nccl_comm_unique_ptr_t(raw, nccl_comm_deleter_t{mp.device_id});
}

